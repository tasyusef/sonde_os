/**
 * Bake the home globe's land mask from Natural Earth's 110m land polygons
 * (public domain, https://www.naturalearthdata.com).
 *
 * Rasterizes the polygons onto an equirectangular grid (`W` × `H`, row 0 at
 * the north edge, column 0 at 180°W) by even-odd scanline fill at each
 * cell's centre, then run-length encodes each row. Output:
 * `src/components/home/Globe/land.ts`, decoded by `lib/globe.ts`.
 *
 * Usage:
 *   pnpm exec tsx scripts/globe-land.ts path/to/ne_110m_land.geojson
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { encodeRuns, LAND_H, LAND_W } from "../src/lib/globe";

type Ring = [number, number][];
type Geometry =
  | { type: "Polygon"; coordinates: Ring[] }
  | { type: "MultiPolygon"; coordinates: Ring[][] };

const src = process.argv[2];
if (!src) {
  console.error("Usage: tsx scripts/globe-land.ts <ne_110m_land.geojson>");
  process.exit(1);
}

const geo = JSON.parse(readFileSync(src, "utf8")) as {
  features: { geometry: Geometry }[];
};

// Every ring's edges; even-odd fill makes holes (lakes) work unaided.
const edges: [number, number, number, number][] = [];
for (const { geometry } of geo.features) {
  const polys = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      for (let i = 0; i < ring.length - 1; i++) {
        const [x0, y0] = ring[i];
        const [x1, y1] = ring[i + 1];
        edges.push([x0, y0, x1, y1]);
      }
    }
  }
}

const rows: Uint8Array[] = [];
for (let r = 0; r < LAND_H; r++) {
  const lat = 90 - ((r + 0.5) * 180) / LAND_H;
  const xs: number[] = [];
  for (const [x0, y0, x1, y1] of edges) {
    if (y0 > lat === y1 > lat) continue;
    xs.push(x0 + ((lat - y0) / (y1 - y0)) * (x1 - x0));
  }
  xs.sort((a, b) => a - b);
  const row = new Uint8Array(LAND_W);
  for (let c = 0; c < LAND_W; c++) {
    const lon = -180 + ((c + 0.5) * 360) / LAND_W;
    let inside = false;
    for (const x of xs) {
      if (x > lon) break;
      inside = !inside;
    }
    row[c] = inside ? 1 : 0;
  }
  rows.push(row);
}

const runs = encodeRuns(rows);
const out = resolve(import.meta.dirname, "../src/components/home/Globe/land.ts");
writeFileSync(
  out,
  `// Generated by scripts/globe-land.ts from Natural Earth's 110m land
// polygons (public domain). Don't edit by hand.

/** The land mask, run-length encoded (see \`decodeRuns\` in \`lib/globe.ts\`). */
export const LAND_RUNS =
  ${JSON.stringify(runs)};
`,
);
console.log(`Wrote ${out} (${runs.length} chars)`);
